def tr(key, **values):
    text = _TEXT[_LANGUAGE].get(key, _TEXT["tr"].get(key, key))
    return text.format(**values)


def toggle_language():
    global _LANGUAGE
    _LANGUAGE = "en" if _LANGUAGE == "tr" else "tr"
    return _LANGUAGE


def current_language():
    return _LANGUAGE


def set_language(language):
    global _LANGUAGE
    if language in _TEXT:
        _LANGUAGE = language
    return _LANGUAGE
